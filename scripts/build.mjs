import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const modules = ['core.js', 'theme.js', 'styles.js', 'storage.js', 'client.source.js'];
const source = await Promise.all(modules.map(name => readFile(resolve(root, name), 'utf8')));
const dictionaries = {};
for (const locale of ['zh', 'en']) {
  dictionaries[locale] = JSON.parse(await readFile(resolve(root, 'locale', `${locale}.json`), 'utf8'));
}
const digest = createHash('sha256').update(source.join('\n') + JSON.stringify(dictionaries)).digest('hex').slice(0, 16);
const body = source.map((text, index) => `// ---- ${modules[index]} ----\n${text.replace(/^export /gm, '')}`).join('\n');
const output = `// Generated by npm run build. Source fingerprint: ${digest}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n    const React = require('react');\n${body}\n    const dictionaries = ${JSON.stringify(dictionaries)};\n    return {\n      inject: ['slots', 'theme', 'locale'],\n      apply(ctx) { installE621(ctx, React, dictionaries); },\n    };\n  },\n});\n`;
await writeFile(resolve(root, 'client.js'), output);
console.log(`Built ${manifest.name}@${manifest.version}: ${Buffer.byteLength(output)} bytes (${digest})`);
